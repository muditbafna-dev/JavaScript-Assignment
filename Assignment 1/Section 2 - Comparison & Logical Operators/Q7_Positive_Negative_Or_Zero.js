
// Q7) Positive, Negative or Zero

// Take a number and determine whether it is:
// ● Positive
// ● Negative
// ● Zero


// Answer 7 :

let number = -8;

if (number > 0) {
    console.log(number + " is Positive");
} else if (number < 0) {
    console.log(number + " is Negative");
} else {
    console.log("Number is Zero");
}
