
// Q12) Number Range

// Take a number.
// Check whether the number is between 10 and 100, including both boundaries.

// Example:
// Input: 50
// Output: Number is between 10 and 100



// Answer 12 :

let number = 50;

if (number >= 10 && number <= 100) {
    console.log("Number is between 10 and 100");    
} else {
    console.log("Number is not in between 10 and 100");
}