
// Q7)  Display Technologies Using forEach()

// Create an array of frontend technologies and use forEach() to display every technology.

// Example:

// Input:

// ["HTML", "CSS", "JavaScript"]

// Output:

// HTML
// CSS
// JavaScript


// Answer 7 :


let technologies = ["HTML", "CSS", "JavaScript"];

technologies.forEach(function(tech) {
    console.log(tech);
});