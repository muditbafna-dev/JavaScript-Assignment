
// Q4)  Dynamic Property Access

// Store a property name in a variable and use bracket notation to access that property from an object.

// Example:

// Input:

// const user = {
//  name: "Rahul",
//  email: "rahul@example.com"
// };
// const key = "name";

// Output:

// Rahul


// Answer 4 :


const user = {
    name: "Rahul",
    email: "rahul@example.com"
};

const key = "name";
console.log(user[key]);
