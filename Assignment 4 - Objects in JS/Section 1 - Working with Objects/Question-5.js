
// Q5) Update an Object Property

// Create a user object with name and role. Update the role from "student" to "developer" and display the updated object.

// Example:

// Input:

// {
//  name: "Rahul",
//  role: "student"
// }
// Output:
// {
//  name: "Rahul",
//  role: "developer"
// }


// Answer 5 :


let user = {
    name: "Rahul",
    role: "student"
};

user.role = "developer";

console.log(user);