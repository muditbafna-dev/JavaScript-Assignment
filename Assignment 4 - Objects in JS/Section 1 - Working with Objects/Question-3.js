
// Q3)  Access Object Properties Using Bracket Notation

// Create a user object containing name and email. Use bracket notation to display the email property.

// Example:

// Input:

// const user = {
//  name: "Rahul",
//  email: "rahul@example.com"
// };

// Output:

// rahul@example.com


// Answer 3 :


